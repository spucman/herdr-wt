"""Release engineering commands; never used when running the plugin."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import tempfile
import tomllib
import zipfile


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "dist"
TARGETS = {
    "linux-x86_64": ("ubuntu-24.04", "x86_64-unknown-linux-musl"),
    "linux-aarch64": ("ubuntu-24.04-arm", "aarch64-unknown-linux-musl"),
    "macos-x86_64": ("macos-15-intel", "x86_64-apple-darwin"),
    "macos-aarch64": ("macos-15", "aarch64-apple-darwin"),
    "windows-x86_64": ("windows-2022", "x86_64-pc-windows-msvc"),
}
TAG = re.compile(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\Z")


def version(tag):
    match = TAG.fullmatch(tag)
    if not match:
        raise SystemExit(f"not a stable vX.Y.Z tag: {tag}")
    return tuple(map(int, match.groups()))


def run(*args, **kw):
    return subprocess.run(args, cwd=ROOT, check=True, text=True, **kw)


def manifest(text, tag, *, linked=False):
    text, count = re.subn(r'^version = "[^"]+"$', f'version = "{tag[1:]}"', text, flags=re.M)
    if count != 1:
        raise SystemExit("expected exactly one manifest version")
    if linked:
        text = re.sub(r"\n\[\[build\]\]\n.*?(?=\n\[\[)", "\n", text, flags=re.S)
    return text


def asset(target):
    return f"herdr-wt-{target}.{'zip' if target.startswith('windows-') else 'tar.gz'}"


def sha256(path):
    with path.open("rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def validate(tag):
    version(tag)
    with (ROOT / "Cargo.toml").open("rb") as f:
        if f"v{tomllib.load(f)['package']['version']}" != tag:
            raise SystemExit("tag does not match the Cargo package version")
    run("git", "merge-base", "--is-ancestor", "HEAD", "origin/main")
    matrix = [
        {"name": k, "runner": v[0], "triple": v[1]} for k, v in TARGETS.items()
    ]
    with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as f:
        print("matrix=" + json.dumps({"include": matrix}, separators=(",", ":")), file=f)


def package(tag, target):
    version(tag)
    triple = TARGETS[target][1]
    windows = target.startswith("windows-")
    binary = "herdr-wt.exe" if windows else "herdr-wt"
    OUT.mkdir(exist_ok=True)
    archive = OUT / asset(target)
    with tempfile.TemporaryDirectory() as temp:
        folder = Path(temp)
        (folder / "bin").mkdir()
        shutil.copy2(ROOT / "target" / triple / "release" / binary, folder / "bin" / binary)
        (folder / "bin" / binary).chmod(0o755)
        (folder / "herdr-plugin.toml").write_text(
            manifest((ROOT / "herdr-plugin.toml").read_text(encoding="utf-8"), tag, linked=True),
            encoding="utf-8",
        )
        shutil.copy2(ROOT / "LICENSE", folder)
        shutil.copy2(ROOT / "README.md", folder)
        shutil.copy2(ROOT / ".herdr-wt.example.toml", folder)
        members = ["herdr-plugin.toml", f"bin/{binary}", "LICENSE", "README.md", ".herdr-wt.example.toml"]
        if windows:
            with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as handle:
                for member in members:
                    handle.write(folder / member, member)
        else:
            with tarfile.open(archive, "w:gz") as handle:
                for member in members:
                    handle.add(folder / member, member)


def pin_text(tag, repo, folder, targets):
    version(tag)
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9_.-]+", repo):
        raise SystemExit("invalid GitHub repository")
    hashes = [
        f"{sha256(folder / asset(target))}  {asset(target)}"
        for target in sorted(targets)
    ]
    return "\n".join(
        ["# Generated by release promotion. Do not update before the assets are published.", tag, repo, *hashes, ""]
    )


def checksums(folder):
    rows = []
    for target in sorted(TARGETS):
        name = asset(target)
        rows.append(f"{sha256(folder / name)}  {name}\n")
    (folder / "SHA256SUMS").write_text("".join(rows), encoding="ascii", newline="\n")


def verify_assets(folder):
    expected = {
        asset(target): sha256(folder / asset(target)) for target in TARGETS
    }
    sums = (folder / "SHA256SUMS").read_text(encoding="ascii").splitlines()
    if sorted(sums) != sorted(f"{digest}  {name}" for name, digest in expected.items()):
        raise SystemExit("published SHA256SUMS does not match the five expected assets")


def promote(tag, repo, folder):
    pin = ROOT / "release-pin"
    previous = pin.read_text(encoding="utf-8").splitlines()[1]
    if previous != "unpublished" and version(previous) >= version(tag):
        raise SystemExit(f"{previous} already promoted; will not promote {tag}")
    content = pin_text(tag, repo, folder, TARGETS)
    manifest_path = ROOT / "herdr-plugin.toml"
    manifest_path.write_text(manifest(manifest_path.read_text(encoding="utf-8"), tag), encoding="utf-8")
    pin.write_text(content, encoding="ascii", newline="\n")


def check_promotion(base, branch):
    expected = branch.removeprefix("release/promote-")
    pinned = (ROOT / "release-pin").read_text(encoding="utf-8").splitlines()[1]
    previous = run("git", "show", f"{base}:release-pin", capture_output=True).stdout.splitlines()[1]
    if pinned != expected or previous != "unpublished" and version(previous) >= version(pinned):
        raise SystemExit(f"refusing a stale or mismatched release promotion: {previous} -> {pinned}")
    with (ROOT / "herdr-plugin.toml").open("rb") as f:
        if f"v{tomllib.load(f)['version']}" != pinned:
            raise SystemExit("manifest and release pin disagree")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate").add_argument("tag")
    pkg = sub.add_parser("package")
    pkg.add_argument("tag")
    pkg.add_argument("target", choices=TARGETS)
    sub.add_parser("checksums").add_argument("folder", type=Path)
    sub.add_parser("verify-assets").add_argument("folder", type=Path)
    promotion = sub.add_parser("promote")
    promotion.add_argument("tag")
    promotion.add_argument("repo")
    promotion.add_argument("folder", type=Path)
    check = sub.add_parser("check-promotion")
    check.add_argument("base")
    check.add_argument("branch")
    values = vars(parser.parse_args())
    command = values.pop("command").replace("-", "_")
    globals()[command](**values)
